use std::collections::{HashMap, HashSet};
use std::fs::{File, Metadata};
use std::hash::Hash;
use std::io::{self, Read, Seek, SeekFrom};
use std::path::PathBuf;
use std::time::UNIX_EPOCH;

use rayon::prelude::*;
use walkdir::WalkDir;

/// The first round only reads this much, so files with different headers split off cheaply.
const FIRST_CHUNK_BYTES: u64 = 4 * 1024;
/// Each later round reads 8x more than the previous one, capped here.
const MAX_CHUNK_BYTES: u64 = 64 * 1024 * 1024;
/// OS metadata files: identical everywhere, regenerated automatically, never worth reviewing.
const IGNORED_FILES: &[&str] = &[".DS_Store", "Thumbs.db", "desktop.ini", ".localized"];
/// Always-skipped folders, matched against the trailing components of a path (so `android/build`
/// only matches a `build` folder directly inside an `android` folder):
/// - VCS internals: "duplicates" in here are load-bearing, deleting them corrupts the repo.
/// - Dependency and build output: regenerated by tooling and full of intentional copies.
const IGNORED_DIRS: &[&str] = &[".git", ".hg", ".svn", "node_modules", "android/build"];

#[derive(Debug, Clone)]
pub struct FileEntry {
    pub id: usize,
    pub path: PathBuf,
    /// Index into the roots passed to `find_duplicates`.
    pub root: usize,
    /// Seconds since the Unix epoch.
    pub modified: Option<u64>,
}

#[derive(Debug, Clone)]
pub struct DuplicateGroup {
    /// Hex-encoded content fingerprint: a BLAKE3 hash chained over the file's chunks.
    pub hash: String,
    pub size: u64,
    pub files: Vec<FileEntry>,
}

impl DuplicateGroup {
    pub fn wasted_bytes(&self) -> u64 {
        self.size * (self.files.len() as u64).saturating_sub(1)
    }
}

#[derive(Debug, Default, Clone, Copy)]
pub struct ScanStats {
    pub files_seen: usize,
    pub bytes_seen: u64,
    /// Files that could not be read (permissions, vanished mid-scan, ...).
    pub unreadable: usize,
}

#[derive(Debug, Clone, Default)]
pub struct ScanOptions {
    /// Files smaller than this are ignored.
    pub min_size: u64,
    /// File or folder names (or trailing paths like `ios/Pods`) skipped wherever they appear.
    pub exclude: Vec<String>,
}

#[derive(Debug)]
pub struct ScanResult {
    pub groups: Vec<DuplicateGroup>,
    pub stats: ScanStats,
}

struct Candidate {
    path: PathBuf,
    root: usize,
    size: u64,
    modified: Option<u64>,
    /// Bytes hashed so far.
    hashed: u64,
    /// Fingerprint of the first `hashed` bytes, chained chunk by chunk.
    digest: [u8; 32],
}

/// Recursively scans every root and returns groups of files with identical contents,
/// sorted by reclaimable space (largest first).
///
/// Files are first grouped by size (metadata only, no reads). Each size group is then split
/// by incremental hashing: every round hashes the next chunk of each file (4 KiB, then 32 KiB,
/// 256 KiB, ... up to 64 MiB) and splits the group by the chained digest. A file stops being
/// read as soon as it no longer matches any other file, and no byte is ever read twice, so
/// only true duplicates are read in full, which is the minimum needed to prove them identical.
pub fn find_duplicates(roots: &[PathBuf], options: &ScanOptions) -> ScanResult {
    let (candidates, mut stats) = collect_files(roots, options);

    let (by_size, _) = regroup(vec![candidates], |c| Ok(c.size));
    let mut pending = without_keys(by_size);
    let mut finished = Vec::new();
    let mut chunk = FIRST_CHUNK_BYTES;
    while !pending.is_empty() {
        let (split, unreadable) = regroup(pending, |c| hash_next_chunk(c, chunk));
        stats.unreadable += unreadable;
        pending = Vec::new();
        // Files in a group share a size, so they all finish in the same round.
        for (digest, group) in split {
            if group[0].hashed == group[0].size {
                finished.push((digest, group));
            } else {
                pending.push(group);
            }
        }
        chunk = (chunk * 8).min(MAX_CHUNK_BYTES);
    }

    let mut groups: Vec<DuplicateGroup> = finished
        .into_iter()
        .map(|(hash, mut files)| {
            files.sort_by(|a, b| a.path.cmp(&b.path));
            DuplicateGroup {
                hash: blake3::Hash::from_bytes(hash).to_hex().to_string(),
                size: files[0].size,
                files: files
                    .into_iter()
                    .map(|c| FileEntry {
                        id: 0,
                        path: c.path,
                        root: c.root,
                        modified: c.modified,
                    })
                    .collect(),
            }
        })
        .collect();

    groups.sort_by(|a, b| {
        b.wasted_bytes()
            .cmp(&a.wasted_bytes())
            .then_with(|| a.hash.cmp(&b.hash))
    });
    for (id, file) in groups.iter_mut().flat_map(|g| g.files.iter_mut()).enumerate() {
        file.id = id;
    }

    ScanResult { groups, stats }
}

fn collect_files(roots: &[PathBuf], options: &ScanOptions) -> (Vec<Candidate>, ScanStats) {
    let mut stats = ScanStats::default();
    let mut seen_paths = HashSet::new();
    let mut seen_inodes = HashSet::new();
    let mut candidates = Vec::new();

    for (root_index, root) in roots.iter().enumerate() {
        let walker = WalkDir::new(root)
            .follow_links(false)
            .into_iter()
            .filter_entry(|e| !is_ignored(e, &options.exclude));
        for entry in walker {
            let Ok(entry) = entry else {
                stats.unreadable += 1;
                continue;
            };
            if !entry.file_type().is_file() {
                continue;
            }
            let Ok(meta) = entry.metadata() else {
                stats.unreadable += 1;
                continue;
            };
            // Overlapping roots (one folder inside another) would otherwise report a file
            // as its own duplicate; hard links share storage so deleting one frees nothing.
            if !seen_paths.insert(entry.path().to_path_buf()) {
                continue;
            }
            if let Some(identity) = file_identity(&meta)
                && !seen_inodes.insert(identity)
            {
                continue;
            }

            stats.files_seen += 1;
            stats.bytes_seen += meta.len();
            if meta.len() < options.min_size {
                continue;
            }
            candidates.push(Candidate {
                path: entry.into_path(),
                root: root_index,
                size: meta.len(),
                modified: meta
                    .modified()
                    .ok()
                    .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
                    .map(|d| d.as_secs()),
                hashed: 0,
                digest: [0; 32],
            });
        }
    }

    (candidates, stats)
}

fn is_ignored(entry: &walkdir::DirEntry, exclude: &[String]) -> bool {
    if entry.depth() == 0 {
        return false;
    }
    let path = entry.path();
    if exclude.iter().any(|excluded| path.ends_with(excluded)) {
        return true;
    }
    let name = entry.file_name().to_string_lossy();
    if entry.file_type().is_dir() {
        IGNORED_DIRS.iter().any(|ignored| path.ends_with(ignored))
    } else {
        // `._name` files are macOS AppleDouble resource forks on non-HFS volumes.
        IGNORED_FILES.contains(&name.as_ref()) || name.starts_with("._")
    }
}

#[cfg(unix)]
fn file_identity(meta: &Metadata) -> Option<(u64, u64)> {
    use std::os::unix::fs::MetadataExt;
    Some((meta.dev(), meta.ino()))
}

#[cfg(not(unix))]
fn file_identity(_meta: &Metadata) -> Option<(u64, u64)> {
    None
}

fn without_keys<K>(groups: Vec<(K, Vec<Candidate>)>) -> Vec<Vec<Candidate>> {
    groups.into_iter().map(|(_, group)| group).collect()
}

/// Splits every group further by `key` (computed in parallel), dropping groups that end up
/// with a single file. Returns the new keyed groups and the number of files whose key failed.
fn regroup<K, F>(groups: Vec<Vec<Candidate>>, key: F) -> (Vec<(K, Vec<Candidate>)>, usize)
where
    K: Eq + Hash + Send,
    F: Fn(&mut Candidate) -> io::Result<K> + Sync,
{
    let flattened: Vec<(usize, Candidate)> = groups
        .into_iter()
        .enumerate()
        .flat_map(|(index, group)| group.into_iter().map(move |c| (index, c)))
        .collect();
    let total = flattened.len();

    let keyed: Vec<((usize, K), Candidate)> = flattened
        .into_par_iter()
        .filter_map(|(index, mut c)| key(&mut c).ok().map(|k| ((index, k), c)))
        .collect();
    let failed = total - keyed.len();

    let mut buckets: HashMap<(usize, K), Vec<Candidate>> = HashMap::new();
    for (k, c) in keyed {
        buckets.entry(k).or_default().push(c);
    }
    let groups = buckets
        .into_iter()
        .filter(|(_, g)| g.len() > 1)
        .map(|((_, k), g)| (k, g))
        .collect();
    (groups, failed)
}

/// Hashes the next `chunk` bytes of the file and chains them into its digest:
/// `digest = BLAKE3(previous digest || chunk bytes)`. Only 32 bytes of state are kept per file,
/// and the file is reopened each round so huge candidate sets never exhaust file handles.
fn hash_next_chunk(c: &mut Candidate, chunk: u64) -> io::Result<[u8; 32]> {
    let len = chunk.min(c.size - c.hashed);
    let mut file = File::open(&c.path)?;
    file.seek(SeekFrom::Start(c.hashed))?;

    let mut hasher = blake3::Hasher::new();
    hasher.update(&c.digest);
    let mut reader = file.take(len);
    hasher.update_reader(&mut reader)?;
    if reader.limit() != 0 {
        return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "file shrank during scan"));
    }

    c.hashed += len;
    c.digest = *hasher.finalize().as_bytes();
    Ok(c.digest)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::path::Path;

    fn min_size(min_size: u64) -> ScanOptions {
        ScanOptions {
            min_size,
            exclude: Vec::new(),
        }
    }

    fn write(dir: &Path, rel: &str, contents: &[u8]) -> PathBuf {
        let path = dir.join(rel);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, contents).unwrap();
        path
    }

    #[test]
    fn finds_nested_duplicates_and_ignores_unique_files() {
        let dir = tempfile::tempdir().unwrap();
        write(dir.path(), "a.txt", b"hello world");
        write(dir.path(), "deep/nested/folder/b.txt", b"hello world");
        write(dir.path(), "c.txt", b"hello there");
        write(dir.path(), "same-size.txt", b"hello WORLD");

        let result = find_duplicates(&[dir.path().to_path_buf()], &min_size(1));

        assert_eq!(result.groups.len(), 1);
        assert_eq!(result.groups[0].files.len(), 2);
        assert_eq!(result.groups[0].hash.len(), 64);
        assert_eq!(result.stats.files_seen, 4);
    }

    #[test]
    fn detects_files_that_differ_only_after_the_partial_hash_window() {
        let dir = tempfile::tempdir().unwrap();
        let mut a = vec![7u8; 64 * 1024];
        let b = a.clone();
        write(dir.path(), "a.bin", &a);
        write(dir.path(), "b.bin", &b);
        a[60 * 1024] = 8;
        write(dir.path(), "c.bin", &a);

        let result = find_duplicates(&[dir.path().to_path_buf()], &min_size(1));

        assert_eq!(result.groups.len(), 1);
        let names: Vec<_> = result.groups[0]
            .files
            .iter()
            .map(|f| f.path.file_name().unwrap().to_owned())
            .collect();
        assert_eq!(names, ["a.bin", "b.bin"]);
    }

    #[test]
    fn splits_large_files_that_differ_late_across_several_chunk_rounds() {
        let dir = tempfile::tempdir().unwrap();
        let base = vec![3u8; 3 * 1024 * 1024 + 17];
        write(dir.path(), "copy1.bin", &base);
        write(dir.path(), "copy2.bin", &base);
        let mut tail = base.clone();
        *tail.last_mut().unwrap() = 4;
        write(dir.path(), "differs-at-end.bin", &tail);
        let mut middle = base.clone();
        middle[300 * 1024] = 9;
        write(dir.path(), "differs-in-middle.bin", &middle);

        let result = find_duplicates(&[dir.path().to_path_buf()], &min_size(1));

        assert_eq!(result.groups.len(), 1);
        let names: Vec<_> = result.groups[0]
            .files
            .iter()
            .map(|f| f.path.file_name().unwrap().to_owned())
            .collect();
        assert_eq!(names, ["copy1.bin", "copy2.bin"]);
    }

    #[test]
    fn identical_contents_get_the_same_fingerprint_in_every_scan() {
        let one = tempfile::tempdir().unwrap();
        let two = tempfile::tempdir().unwrap();
        for dir in [&one, &two] {
            write(dir.path(), "a", b"same bytes");
            write(dir.path(), "b", b"same bytes");
        }

        let first = find_duplicates(&[one.path().to_path_buf()], &min_size(1));
        let second = find_duplicates(&[two.path().to_path_buf()], &min_size(1));

        assert_eq!(first.groups[0].hash, second.groups[0].hash);
    }

    #[test]
    fn finds_duplicates_across_multiple_roots() {
        let one = tempfile::tempdir().unwrap();
        let two = tempfile::tempdir().unwrap();
        write(one.path(), "photo.jpg", b"pixels");
        write(two.path(), "backup/photo-copy.jpg", b"pixels");

        let result = find_duplicates(&[one.path().to_path_buf(), two.path().to_path_buf()], &min_size(1));

        assert_eq!(result.groups.len(), 1);
        let roots: Vec<_> = result.groups[0].files.iter().map(|f| f.root).collect();
        assert_eq!(roots.len(), 2);
        assert!(roots.contains(&0) && roots.contains(&1));
    }

    #[test]
    fn overlapping_roots_do_not_report_a_file_as_its_own_duplicate() {
        let dir = tempfile::tempdir().unwrap();
        write(dir.path(), "sub/only.txt", b"just one copy");

        let result = find_duplicates(&[dir.path().to_path_buf(), dir.path().join("sub")], &min_size(1));

        assert!(result.groups.is_empty());
    }

    #[test]
    fn skips_os_metadata_files_and_version_control_folders() {
        let dir = tempfile::tempdir().unwrap();
        for folder in ["a", "b"] {
            write(dir.path(), &format!("{folder}/.DS_Store"), b"finder junk");
            write(dir.path(), &format!("{folder}/._photo.jpg"), b"resource fork");
            write(dir.path(), &format!("{folder}/.git/objects/ab/cdef"), b"git object");
        }

        let result = find_duplicates(&[dir.path().to_path_buf()], &min_size(1));

        assert!(result.groups.is_empty());
        assert_eq!(result.stats.files_seen, 0);
    }

    #[test]
    fn skips_excluded_names_anywhere_in_the_tree() {
        let dir = tempfile::tempdir().unwrap();
        write(dir.path(), "app/node_modules/lib/index.js", b"module");
        write(dir.path(), "other/node_modules/lib/index.js", b"module");
        write(dir.path(), "keep/a.txt", b"real duplicate");
        write(dir.path(), "keep/b.txt", b"real duplicate");

        let options = ScanOptions {
            min_size: 1,
            exclude: vec!["node_modules".into()],
        };
        let result = find_duplicates(&[dir.path().to_path_buf()], &options);

        assert_eq!(result.groups.len(), 1);
        assert!(result.groups[0].files[0].path.ends_with("keep/a.txt"));
    }

    #[test]
    fn always_skips_node_modules_and_android_build_but_not_other_build_folders() {
        let dir = tempfile::tempdir().unwrap();
        for app in ["one", "two"] {
            write(dir.path(), &format!("{app}/node_modules/lib/index.js"), b"module");
            write(dir.path(), &format!("{app}/android/build/outputs/app.apk"), b"apk");
            write(dir.path(), &format!("{app}/build/report.txt"), b"kept build output");
        }

        let result = find_duplicates(&[dir.path().to_path_buf()], &min_size(1));

        assert_eq!(result.groups.len(), 1);
        assert!(
            result.groups[0]
                .files
                .iter()
                .all(|f| f.path.ends_with("build/report.txt"))
        );
        assert_eq!(result.stats.files_seen, 2);
    }

    #[test]
    fn exclude_accepts_trailing_paths() {
        let dir = tempfile::tempdir().unwrap();
        for app in ["one", "two"] {
            write(dir.path(), &format!("{app}/ios/Pods/lib.a"), b"pod");
            write(dir.path(), &format!("{app}/Pods/readme.txt"), b"not under ios");
        }

        let options = ScanOptions {
            min_size: 1,
            exclude: vec!["ios/Pods".into()],
        };
        let result = find_duplicates(&[dir.path().to_path_buf()], &options);

        assert_eq!(result.groups.len(), 1);
        assert!(result.groups[0].files[0].path.ends_with("Pods/readme.txt"));
    }

    #[cfg(unix)]
    #[test]
    fn hard_links_are_not_reported_as_duplicates() {
        let dir = tempfile::tempdir().unwrap();
        let original = write(dir.path(), "original.txt", b"shared inode");
        fs::hard_link(&original, dir.path().join("link.txt")).unwrap();

        let result = find_duplicates(&[dir.path().to_path_buf()], &min_size(1));

        assert!(result.groups.is_empty());
    }

    #[test]
    fn respects_min_size_and_assigns_unique_ids_sorted_by_wasted_space() {
        let dir = tempfile::tempdir().unwrap();
        write(dir.path(), "small1", b"ab");
        write(dir.path(), "small2", b"ab");
        write(dir.path(), "big1", &[1u8; 100]);
        write(dir.path(), "big2", &[1u8; 100]);
        write(dir.path(), "empty1", b"");
        write(dir.path(), "empty2", b"");

        let result = find_duplicates(&[dir.path().to_path_buf()], &min_size(1));

        assert_eq!(result.groups.len(), 2);
        assert_eq!(result.groups[0].size, 100);
        let ids: Vec<_> = result
            .groups
            .iter()
            .flat_map(|g| g.files.iter().map(|f| f.id))
            .collect();
        assert_eq!(ids, [0, 1, 2, 3]);

        let only_big = find_duplicates(&[dir.path().to_path_buf()], &min_size(50));
        assert_eq!(only_big.groups.len(), 1);
    }
}
